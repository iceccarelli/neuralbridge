"""Article 14 deadlines: the counting rule, its guard, and the basis printed beside every deadline.

Audit findings F1-F3 of the legal review of the clocks.

F1  The incident final report is due "within one month after the submission of the incident
    notification" (Art. 14(4)(c)). ``add_one_month`` on the UTC instant is NOT never-later than the
    month counted in the submitter's own calendar (Reg. (EEC, Euratom) No 1182/71 Art. 3(2)(c): the
    period ends with the expiry of the last hour of the day with the same date one month on):
    ``2027-02-28T23:11-08:00`` is ``2027-03-01T07:11Z`` in UTC, and a month from 1 March ends on
    1 April, three days after 28 March + 1 month ended at the submitter's. The due time is now the
    earliest over every fixed UTC offset (-12:00 .. +14:00, 15-minute grid). The 24 h, 72 h and
    14 d due times are not touched and are pinned byte-for-byte against the build that preceded
    the change (the golden rows below were generated by that build).
F2  Every deadline carries a ``basis``: the provision and its wording, how it is counted, from
    which recorded fact, what else the provision requires, and other legal readings that are
    shown for information and never replace ``due_at``.
F3  The notes about the ENISA platform name their source and date and do not overstate.

The oracle in this file is written independently of ``clock.py`` (it builds the end of the local
day with ``datetime.astimezone`` rather than by offset arithmetic).
"""

from __future__ import annotations

import calendar
from datetime import UTC, date, datetime, timedelta, timezone

import pytest

from assurance.core.identity import format_utc, parse_utc
from assurance.security.art14.clock import (
    EARLY_WARNING_HOURS,
    NOTIFICATION_HOURS,
    VULNERABILITY_FINAL_DAYS,
    Deadlines,
    add_one_month,
    incident_final_due_at,
)
from assurance.security.art14.model import Track
from assurance.security.art14.timestamps import legal_timestamp

GRID = [timedelta(minutes=m) for m in range(-12 * 60, 14 * 60 + 1, 15)]
GRID_TZ = [timezone(off) for off in GRID]


# --------------------------------------------------------------------------------------------
# the oracle: Reg. 1182/71 Art. 3(2)(c) in the calendar of a clock at a given fixed UTC offset
# --------------------------------------------------------------------------------------------
def end_of_same_date_one_month_on(instant: datetime, tz) -> datetime:
    local = instant.astimezone(tz)
    year, month = (local.year + 1, 1) if local.month == 12 else (local.year, local.month + 1)
    day = min(local.day, calendar.monthrange(year, month)[1])
    nxt = date(year, month, day) + timedelta(days=1)
    return datetime(nxt.year, nxt.month, nxt.day, tzinfo=tz).astimezone(UTC)


def readings_over_grid(instant: datetime) -> list[datetime]:
    return [end_of_same_date_one_month_on(instant, tz) for tz in GRID_TZ]


def month_due(notification_at: datetime) -> datetime:
    return Deadlines(
        track=Track.INCIDENT, awareness_at=notification_at - timedelta(hours=1),
        notification_submitted_at=notification_at,
    ).final.due_at


def _sample_instants():
    """A bounded, deterministic sample: a coarse sweep plus 20-minute steps around month ends."""
    t = parse_utc("2026-09-11T00:00:00Z")
    stop = parse_utc("2028-12-31T00:00:00Z")
    while t < stop:
        yield t
        t += timedelta(minutes=211)
    for year, month in [(2026, 9), (2026, 12), (2027, 2), (2027, 3), (2027, 8), (2027, 10),
                        (2027, 12), (2028, 1), (2028, 2), (2028, 3)]:
        last = calendar.monthrange(year, month)[1]
        t = datetime(year, month, last, tzinfo=UTC) - timedelta(hours=14)
        while t < datetime(year, month, last, tzinfo=UTC) + timedelta(hours=38):
            yield t
            t += timedelta(minutes=20)


SAMPLE = tuple(_sample_instants())


def sample_instants():
    return SAMPLE


# --------------------------------------------------------------------------------------------
# F1: the audit's two examples, as the parser produces them
# --------------------------------------------------------------------------------------------
class TestTheAuditedExamples:
    def test_submission_late_on_the_last_day_of_february_in_the_west(self):
        submitted = legal_timestamp("2027-02-28T23:11-08:00")
        assert format_utc(submitted) == "2027-03-01T07:11:00Z"
        old = add_one_month(submitted)
        assert format_utc(old) == "2027-04-01T07:11:00Z"           # what the product used to say
        new = month_due(submitted)
        # the month counted in the submitter's own calendar (-08:00): 28 March, ending 29 March 08:00Z
        assert new <= parse_utc("2027-03-29T08:00:00Z")
        assert old - parse_utc("2027-03-29T08:00:00Z") > timedelta(days=2, hours=23)   # was later
        assert format_utc(new) == "2027-03-29T07:15:00Z"            # pinned: earliest over the grid

    def test_submission_early_on_the_last_day_of_august_in_the_east(self):
        submitted = legal_timestamp("2027-08-31T02:35+03:00")
        assert format_utc(submitted) == "2027-08-30T23:35:00Z"
        old = add_one_month(submitted)
        athens_end = parse_utc("2027-09-30T21:00:00Z")              # end of 30 Sep at +03:00
        assert old - athens_end == timedelta(hours=2, minutes=35)   # the audit's figure
        new = month_due(submitted)
        assert new <= athens_end
        assert format_utc(new) == "2027-09-30T10:00:00Z"            # +14:00 reading

    def test_a_filing_between_the_two_is_recorded_late_and_says_so_in_the_status(self):
        submitted = legal_timestamp("2027-02-28T23:11-08:00")
        d = Deadlines(
            track=Track.INCIDENT, awareness_at=submitted - timedelta(hours=40),
            notification_submitted_at=submitted,
            final_submitted_at=parse_utc("2027-03-30T12:00:00Z"),   # before the old due, after the new
        ).final
        assert d.status == "filed_late" and d.met is False
        assert d.due_at < d.submitted_at < add_one_month(submitted)


