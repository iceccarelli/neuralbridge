class TestMonthGuardProperty:
    def test_never_later_and_exactly_the_earliest_over_every_fixed_offset_calendar(self):
        """The audit's brute-force sweep on a bounded deterministic sample (0 violations).

        "Never later" alone would also be satisfied by an arbitrarily early date, so the value
        is also compared with the earliest of the independent readings.
        """
        checked = changed = 0
        biggest = timedelta(0)
        for instant in sample_instants():
            due = incident_final_due_at(instant)
            old = add_one_month(instant)
            readings = readings_over_grid(instant)
            assert due <= min(readings), instant.isoformat()
            assert due == min([old, *readings]), instant.isoformat()
            assert due <= old
            if due < old:
                changed += 1
                biggest = max(biggest, old - due)
            checked += 1
        assert checked > 6000
        assert 0 < changed < checked * 0.15                      # a minority of instants move
        assert biggest <= timedelta(days=2, hours=23, minutes=59)

    def test_where_the_guard_does_not_bind_the_value_is_the_unchanged_add_one_month(self):
        same = 0
        for instant in sample_instants():
            if incident_final_due_at(instant) == add_one_month(instant):
                same += 1
        assert same > 5000

    def test_the_public_add_one_month_is_unchanged(self):
        assert add_one_month(parse_utc("2027-03-01T07:11:00Z")) == parse_utc("2027-04-01T07:11:00Z")
        assert add_one_month(parse_utc("2024-01-31T10:00:00Z")) == parse_utc("2024-02-29T10:00:00Z")
        assert add_one_month(datetime(2026, 1, 31, 9, 0)) == datetime(2026, 2, 28, 9, 0)   # naive

    @pytest.mark.parametrize("start,expected", [
        ("2026-09-21T09:00:00Z", "2026-10-21T09:00:00Z"),
        ("2025-01-31T10:00:00Z", "2025-02-28T10:00:00Z"),
        ("2024-01-31T10:00:00Z", "2024-02-29T10:00:00Z"),
        ("2025-12-31T23:59:00Z", "2026-01-31T23:59:00Z"),
        ("2026-03-31T00:00:00Z", "2026-04-30T00:00:00Z"),
    ])
    def test_the_established_month_examples_still_hold(self, start, expected):
        assert format_utc(month_due(parse_utc(start))) == expected

    def test_a_month_end_clamp_is_applied_in_each_calendar(self):
        # 30 January 23:30 at -12:00 is 31 January 11:30Z; at -12:00 the date is the 30th, so
        # the month ends with the last day of February (28th in 2027), not 2 March.
        instant = parse_utc("2027-01-31T11:30:00Z")
        assert month_due(instant) <= end_of_same_date_one_month_on(instant, timezone(timedelta(hours=-12)))

    def test_it_does_not_overflow_where_the_old_rule_did_not(self):
        late = datetime(9999, 11, 30, 23, 59, tzinfo=UTC)
        assert incident_final_due_at(late) <= add_one_month(late)
        with pytest.raises(ValueError):                         # the old rule raised here too
            incident_final_due_at(datetime(9999, 12, 15, tzinfo=UTC))

    def test_it_is_stateless_and_repeatable(self):
        instant = parse_utc("2027-03-01T07:11:00Z")
        assert month_due(instant) == month_due(instant) == incident_final_due_at(instant)


class TestDocumentedResidualInZonesWithDaylightSaving:
    """The guard uses a fixed offset for the month; a zone that changes offset inside it differs."""

    ZONES = ["Europe/Berlin", "Europe/Athens", "America/New_York", "America/Los_Angeles",
             "Australia/Sydney", "Pacific/Auckland", "Europe/Dublin", "Atlantic/Azores"]
    FIXED = ["UTC", "Asia/Kolkata", "Asia/Kathmandu", "Asia/Tokyo", "Pacific/Kiritimati",
             "Pacific/Pago_Pago"]

    @staticmethod
    def _end_of_local_day(date_: date, tz) -> datetime:
        nxt = date_ + timedelta(days=1)
        return datetime(nxt.year, nxt.month, nxt.day, tzinfo=tz).astimezone(UTC)

    def _month_target(self, instant: datetime, tz) -> date:
        loc = instant.astimezone(tz)
        year, month = (loc.year + 1, 1) if loc.month == 12 else (loc.year, loc.month + 1)
        return date(year, month, min(loc.day, calendar.monthrange(year, month)[1]))

    def test_month_residual_is_at_most_one_daylight_saving_step(self):
        from zoneinfo import ZoneInfo

        worst = dict.fromkeys(self.ZONES + self.FIXED, timedelta(0))
        zones = {name: ZoneInfo(name) for name in worst}
        for instant in sample_instants()[::2]:
            due = incident_final_due_at(instant)
            for name, tz in zones.items():
                gap = due - self._end_of_local_day(self._month_target(instant, tz), tz)
                worst[name] = max(worst[name], gap)
        for name in self.FIXED:
            assert worst[name] <= timedelta(0), (name, worst[name])     # a fixed-offset zone: never later
        for name in self.ZONES:
            assert worst[name] <= timedelta(hours=1), (name, worst[name])
        assert any(worst[n] > timedelta(0) for n in self.ZONES)           # and the residual is real

    def test_fourteen_days_is_never_later_in_a_fixed_offset_and_under_one_hour_with_dst(self):
        from zoneinfo import ZoneInfo

        t = parse_utc("2026-09-11T00:00:00Z")
        worst = dict.fromkeys(self.ZONES + self.FIXED, timedelta(0))
        zones = {name: ZoneInfo(name) for name in worst}
        while t < parse_utc("2028-12-31T00:00:00Z"):
            due = Deadlines(track=Track.VULNERABILITY, awareness_at=t, measure_available_at=t).final.due_at
            for name, tz in zones.items():
                loc = t.astimezone(tz)
                worst[name] = max(worst[name], due - self._end_of_local_day(loc.date() + timedelta(days=14), tz))
            t += timedelta(minutes=211)
        for name in self.FIXED:
            assert worst[name] <= timedelta(0), (name, worst[name])
        for name in self.ZONES:
            assert worst[name] < timedelta(hours=1), (name, worst[name])
        assert any(worst[n] > timedelta(0) for n in self.ZONES)           # the residual is real


