GRID = [timedelta(minutes=m) for m in range(-12 * 60, 14 * 60 + 1, 15)]
GRID_TZ = [timezone(off) for off in GRID]


# --------------------------------------------------------------------------------------------
# the oracle: Reg. 1182/71 Art. 3(2)(c) in the calendar of a clock at a given fixed UTC offset
# --------------------------------------------------------------------------------------------
def end_of_same_date_one_month_on(instant: datetime, tz) -> datetime:
    local = instant.astimezone(tz)
    year, month = (local.year + 1, 1) if local.month == 12 else (local.year, local.month + 1)
    day = min(local.day, calendar.monthrange(year, month)[1])
    nxt = date(year, month, day) + timedelta(days=1)
    return datetime(nxt.year, nxt.month, nxt.day, tzinfo=tz).astimezone(UTC)


def readings_over_grid(instant: datetime) -> list[datetime]:
    return [end_of_same_date_one_month_on(instant, tz) for tz in GRID_TZ]


def month_due(notification_at: datetime) -> datetime:
    return Deadlines(
        track=Track.INCIDENT, awareness_at=notification_at - timedelta(hours=1),
        notification_submitted_at=notification_at,
    ).final.due_at


def _sample_instants():
    """A bounded, deterministic sample: a coarse sweep plus 20-minute steps around month ends."""
    t = parse_utc("2026-09-11T00:00:00Z")
    stop = parse_utc("2028-12-31T00:00:00Z")
    while t < stop:
        yield t
        t += timedelta(minutes=211)
    for year, month in [(2026, 9), (2026, 12), (2027, 2), (2027, 3), (2027, 8), (2027, 10),
                        (2027, 12), (2028, 1), (2028, 2), (2028, 3)]:
        last = calendar.monthrange(year, month)[1]
        t = datetime(year, month, last, tzinfo=UTC) - timedelta(hours=14)
        while t < datetime(year, month, last, tzinfo=UTC) + timedelta(hours=38):
            yield t
            t += timedelta(minutes=20)


SAMPLE = tuple(_sample_instants())


def sample_instants():
    return SAMPLE


