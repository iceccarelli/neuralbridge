class TestHoursAndDaysAreUntouched:
    @pytest.mark.parametrize("row", GOLDEN, ids=[r[0] for r in GOLDEN])
    def test_golden_rows_from_the_previous_build(self, row):
        at, ew, notif, final14, old_month = row
        t = parse_utc(at)
        vuln = Deadlines(track=Track.VULNERABILITY, awareness_at=t, measure_available_at=t)
        inc = Deadlines(track=Track.INCIDENT, awareness_at=t, notification_submitted_at=t)
        assert format_utc(vuln.early_warning.due_at) == ew == format_utc(inc.early_warning.due_at)
        assert format_utc(vuln.notification.due_at) == notif == format_utc(inc.notification.due_at)
        assert format_utc(vuln.final.due_at) == final14
        assert vuln.early_warning.to_dict()["due_at"] == ew            # the serialised form too
        assert vuln.final.to_dict()["due_at"] == final14
        assert inc.final.due_at <= parse_utc(old_month)                # the guard only moves earlier
        if (at, old_month) in {("2026-09-19T06:30:00Z", "2026-10-19T06:30:00Z"),
                               ("2027-01-31T10:00:00Z", "2027-02-28T10:00:00Z"),
                               ("2027-03-31T12:00:00Z", "2027-04-30T12:00:00Z")}:
            assert format_utc(inc.final.due_at) == old_month           # not bound: byte-identical

    def test_over_the_whole_sample_hours_and_days_are_exactly_t_plus_the_period(self):
        for t in sample_instants():
            vuln = Deadlines(track=Track.VULNERABILITY, awareness_at=t, measure_available_at=t)
            inc = Deadlines(track=Track.INCIDENT, awareness_at=t, notification_submitted_at=t)
            for d in (vuln, inc):
                assert d.early_warning.due_at == t + timedelta(hours=EARLY_WARNING_HOURS)
                assert d.notification.due_at == t + timedelta(hours=NOTIFICATION_HOURS)
            assert vuln.final.due_at == t + timedelta(days=VULNERABILITY_FINAL_DAYS)
            assert (
                format_utc(vuln.final.due_at)
                == format_utc(t + timedelta(days=14))
            )
