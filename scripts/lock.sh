#!/usr/bin/env bash
# Regenerate the hash-pinned Python lock files from requirements/*.txt.
#
#   scripts/lock.sh            keep every version already pinned in the committed lock,
#                              resolve only what changed in the .txt inputs
#   scripts/lock.sh --upgrade  re-resolve everything to the newest allowed versions
#   scripts/lock.sh --check    write nothing; exit 1 if a lock differs from what the
#                              inputs resolve to (used by the CI "Lock drift" job)
#
# Requires uv (https://docs.astral.sh/uv/). Uses the default package index (PyPI) only:
# no --index-url / --extra-index-url is passed, and none may be added without review.
#
# Lock files and the interpreter each targets (all --universal: environment markers cover
# linux amd64 and arm64, which publish-docker.yml builds, plus macOS and Windows):
#   requirements/prod.lock               <- requirements/prod.txt              universal, >=3.11
#       (root Dockerfile: python:3.11-slim; the NeuralBridge platform)
#   requirements/assurance-service.lock  <- requirements/assurance-service.txt universal, >=3.12
#       (deploy/assurance/Dockerfile: python:3.12-slim; the assurance service)
#   requirements/test.lock               <- requirements/test.txt              universal >=3.11
#       (CI test matrix is 3.11, 3.12, 3.13; markers keep one file valid for all)
#
# Pins are the lock; the .txt files stay as the human-edited lower bounds. Edit a .txt,
# run this script, commit both. tests/test_requirements_lock.py fails if you forget.
set -euo pipefail

cd "$(dirname "$0")/.."

mode=keep
case "${1:-}" in
  "") ;;
  --upgrade) mode=upgrade ;;
  --check) mode=check ;;
  *) echo "usage: scripts/lock.sh [--upgrade|--check]" >&2; exit 2 ;;
esac

command -v uv >/dev/null || { echo "uv not found: pip install uv" >&2; exit 2; }

# name | input | extra uv args
specs=(
  "prod|requirements/prod.txt|--universal --python-version 3.11"
  "assurance-service|requirements/assurance-service.txt|--universal --python-version 3.12"
  "test|requirements/test.txt|--universal --python-version 3.11"
)

status=0
for spec in "${specs[@]}"; do
  IFS='|' read -r name input args <<<"$spec"
  out="requirements/${name}.lock"
  tmp="$(mktemp)"
  # uv treats an existing output file as preferred pins, so seeding the temp file with
  # the committed lock makes a plain re-run stable until an input actually changes.
  if [ "$mode" != upgrade ] && [ -f "$out" ]; then cp "$out" "$tmp"; fi
  upgrade=""
  [ "$mode" = upgrade ] && upgrade="--upgrade"
  # shellcheck disable=SC2086
  PYTHONDONTWRITEBYTECODE=1 uv pip compile "$input" -o "$tmp" --generate-hashes \
      --no-header $args $upgrade >/dev/null
  # Header is written by us so it does not depend on the temp path.
  {
    echo "# Generated by scripts/lock.sh from ${input} — do not edit by hand."
    echo "# uv pip compile ${input} --generate-hashes --no-header ${args}"
    echo "# Install: pip install --require-hashes --no-deps -r ${out}"
    cat "$tmp"
  } >"${tmp}.full"
  if [ "$mode" = check ]; then
    if ! diff -u "$out" "${tmp}.full"; then
      echo "DRIFT: ${out} does not match ${input}. Run scripts/lock.sh and commit." >&2
      status=1
    else
      echo "ok: ${out}"
    fi
  else
    mv "${tmp}.full" "$out"
    echo "wrote ${out}"
  fi
  rm -f "$tmp" "${tmp}.full"
done
exit $status
