#!/usr/bin/env python3
"""Render docs/integrations.md from the adapter source, so the directory cannot say more than the code does.

Reads src/neuralbridge/adapters/**/*.py with ``ast`` (no adapter SDK has to be installed, which matters because
CI installs none of the MySQL / MongoDB / BigQuery ones). ``tests/test_integrations_directory.py`` fails if the
committed page differs from this output.

    python scripts/export_integrations.py          # write docs/integrations.md
    python scripts/export_integrations.py --check  # exit 1 if it is out of date
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ADAPTERS = ROOT / "src" / "neuralbridge" / "adapters"
OUT = ROOT / "docs" / "integrations.md"

# What each classification means, in the words the site uses. Source of truth: neuralbridge/adapters/base.py.
LABEL = {
    "real": "Supported, with limits",
    "partial": "Experimental (real client path, never run against a live service)",
    "mock": "Experimental (canned: makes no call)",
}


def _consts(cls: ast.ClassDef) -> dict[str, object]:
    out: dict[str, object] = {}
    for node in cls.body:
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            name, value = node.target.id, node.value
        elif isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
            name, value = node.targets[0].id, node.value
        else:
            continue
        if isinstance(value, ast.Constant):
            out[name] = value.value
        elif isinstance(value, ast.List) and all(isinstance(e, ast.Constant) for e in value.elts):
            out[name] = [e.value for e in value.elts]  # type: ignore[attr-defined]
    return out


def inventory() -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for path in sorted(ADAPTERS.rglob("*.py")):
        if path.name in ("__init__.py", "base.py"):
            continue
        for cls in (n for n in ast.parse(path.read_text(encoding="utf-8")).body if isinstance(n, ast.ClassDef)):
            if not any(getattr(b, "id", None) == "BaseAdapter" for b in cls.bases):
                continue
            c = _consts(cls)
            rows.append(
                {
                    "type": c["adapter_type"],
                    "category": c.get("category", "general"),
                    "backend": c.get("backend", "mock"),
                    "ops": c.get("supported_operations", []),
                    "file": path.relative_to(ROOT).as_posix(),
                }
            )
    rows.sort(key=lambda r: (str(r["category"]), str(r["type"])))
    return rows


def render() -> str:
    rows = inventory()
    real = [r for r in rows if r["backend"] == "real"]
    partial = [r for r in rows if r["backend"] == "partial"]
    canned = [r for r in rows if r["backend"] == "mock"]
    lines = [
        "# Integrations",
        "",
        "<!-- Generated by scripts/export_integrations.py from src/neuralbridge/adapters. Do not edit by hand. -->",
        "",
        "Industrial Autonomous Assurance does not need any of these: the offline kit, the CLI, the Assurance API and",
        "the MCP server work on their own. The adapters below belong to the NeuralBridge integration platform it grew",
        "out of, and this page says exactly how far each one goes.",
        "",
        f"**{len(rows)} adapters: {len(real)} supported with limits, {len(partial)} with a real client path that has "
        f"never run against a live service, {len(canned)} canned.** A canned adapter makes no call to the service it is "
        "named after.",
        "",
        "## What the classification means",
        "",
        "| Classification | Meaning | Default behaviour |",
        "|---|---|---|",
        f"| {LABEL['real']} | Calls the real service and is exercised against it by a test. | Runs. |",
        f"| {LABEL['partial']} | A real client path exists. | Runs only against the live service; a failed "
        "connection raises an error and never falls back to invented data. |",
        f"| {LABEL['mock']} | Returns canned results. | **Refused** with an error. Opt in for a demo or test with "
        "`allow_mock: true` in the adapter config or `NEURALBRIDGE_ALLOW_MOCK_ADAPTERS=1`; every result is then "
        "flagged `mock: true`. |",
        "",
        "An adapter that is not classified is treated as canned. Promoting one is a code change that "
        "`tests/test_adapter_fail_closed.py` makes a reviewer look at.",
        "",
        "## Directory",
        "",
        "| Adapter | Category | Classification | Operations | Source |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        ops = ", ".join(f"`{o}`" for o in r["ops"]) or "—"  # type: ignore[attr-defined]
        lines.append(f"| `{r['type']}` | {r['category']} | {LABEL[str(r['backend'])]} | {ops} | `{r['file']}` |")
    lines += [
        "",
        "## PostgreSQL (supported, with limits)",
        "",
        "- **Prerequisites:** a reachable PostgreSQL server and the `asyncpg` package (installed with the project).",
        "- **Configuration:** `host`, `port`, `user`, `password`, `database`, `ssl_mode` (default `prefer`), "
        "`pool_size` (default 10).",
        "- **Permissions:** the adapter runs whatever its database role may run. Give it a role that can only do what "
        "you intend. The `/ai` control plane's policy gate (`neuralbridge/ai/guard.py`) treats reads as free, gates "
        "writes and destructive statements behind the `ai_control_plane` entitlement and refuses exfiltration-shaped "
        "SQL, but the database role is the real boundary.",
        "- **Failure modes:** a failed connection raises `ConnectionError`; the adapter never answers from canned "
        "data unless `allow_mock` is set.",
        "- **Limits:** the default `ssl_mode` is `prefer`, which does not refuse an unencrypted connection; set it "
        "explicitly for anything beyond a local test. The tests that run it against a real server "
        "(`tests/test_ai.py`) need PostgreSQL and fail rather than skip when `NEURALBRIDGE_REQUIRE_POSTGRES=1` "
        "(as in CI); they do not cover TLS modes or role permissions.",
        "",
        "## REST (supported, with limits)",
        "",
        "- **What it does:** real GET / POST / PUT / PATCH / DELETE / HEAD through `httpx` with bearer, basic or "
        "API-key header authentication. Credentials come from the adapter config (`credentials`, or "
        "`credentials_env` naming environment variables) and are never logged, put in errors or returned.",
        "- **Bounds:** http(s) only; private, loopback, link-local (including the cloud metadata address) and "
        "reserved destinations are refused unless `allow_private_network` is set; optional `allowed_hosts`; "
        "response size and wall-clock time are capped; redirects to another origin are never followed; a non-2xx "
        "status, a timeout or an oversized body is a structured failure, never a success.",
        "- **Limits:** the address check does not defend against DNS rebinding; ambient proxies are ignored unless "
        "`trust_env` is set. Tested by `tests/test_rest_adapter.py` against a local HTTP server that the test "
        "starts; no third-party API and no TLS certificate handling is covered.",
        "",
        "## What is not claimed",
        "",
        "- No adapter other than PostgreSQL and REST is exercised against a real or locally emulated service by "
        "any test in this repository, and REST has only been run against a local HTTP server started by its own "
        "test.",
        "- The MySQL, MongoDB and BigQuery SDKs are not installed in CI, so those adapters cannot even be imported "
        "there; their failure paths are tested with the SDK modules stubbed, which shows our error handling, not "
        "that they work.",
        "- Supported does not mean certified, and an adapter existing is not a claim that an integration with that "
        "product is available.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        return 0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1
    OUT.write_text(text, encoding="utf-8")
    sys.stdout.write(f"wrote {OUT.relative_to(ROOT)} ({len(inventory())} adapters)\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
